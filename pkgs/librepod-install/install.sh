#!/usr/bin/env bash
# LibrePod appliance installer — run from the netboot installer image.
# Generates the device-owned flake, formats via disko, installs NixOS.
set -euo pipefail

MNT="${LIBREPOD_TARGET_MNT:-/mnt}"
WORKDIR="${LIBREPOD_WORKDIR:-}"
DISKO_BIN="${DISKO_BIN:-disko}"
NIXOS_INSTALL_BIN="${NIXOS_INSTALL_BIN:-nixos-install}"
NIX_BIN="${NIX_BIN:-nix}"
CURL_BIN="${CURL_BIN:-curl}"

usage() {
  echo "usage: librepod-install --device <hw-profile|module.nix> --name <hostname>"
  echo "                        --identity FILE [--os-tag vX.Y.Z] [--disk /dev/nvme0n1]"
  exit 1
}

DEVICE="" NAME="" TAG="" IDENTITY="" DISK="/dev/nvme0n1"
while [ $# -gt 0 ]; do
  case "$1" in
    --device) [ $# -ge 2 ] || usage; DEVICE="$2"; shift 2;;
    --disk) [ $# -ge 2 ] || usage; DISK="$2"; shift 2;;
    --name) [ $# -ge 2 ] || usage; NAME="$2"; shift 2;;
    --os-tag) [ $# -ge 2 ] || usage; TAG="$2"; shift 2;;
    --identity) [ $# -ge 2 ] || usage; IDENTITY="$2"; shift 2;;
    *) usage;;
  esac
done
[ -n "$DEVICE" ] && [ -n "$NAME" ] || usage
[ -n "$IDENTITY" ] || { echo "--identity is required (users/keys live there)"; exit 1; }
# It lands in a Nix string in install.nix.
[[ "$DISK" =~ ^/dev/[A-Za-z0-9/_.-]+$ ]] || { echo "invalid disk: $DISK"; exit 1; }

if [ -z "$TAG" ]; then
  TAG="$("$CURL_BIN" -fsSL https://api.github.com/repos/librepod/os/releases/latest \
    | jq -r .tag_name)" || { echo "could not resolve latest release; pass --os-tag"; exit 1; }
fi
[[ "$TAG" =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo "invalid tag: $TAG"; exit 1; }

WORKDIR="${WORKDIR:-$(mktemp -d)}"
mkdir -p "$WORKDIR"

# String → ./hw/<name> profile; anything path-like is copied in as a single
# hardware module (its imports must be inlined or absolute).
DEVICE_REF="\"$DEVICE\""
case "$DEVICE" in
  */*)
    cp "$DEVICE" "$WORKDIR/hardware.nix"
    DEVICE_REF="./hardware.nix"
    ;;
esac

cat > "$WORKDIR/flake.nix" <<EOF
# Generated by librepod-install — owned by the device.
{
  # ponytail: the updater sed-targets this exact pin line; keep the format
  inputs.librepod.url = "github:librepod/os/${TAG}";
  outputs = { librepod, ... }: {
    nixosConfigurations.${NAME} = librepod.lib.mkDevice {
      name = "${NAME}";
      version = (builtins.fromJSON (builtins.readFile ./flake.lock)).nodes.librepod.original.ref;
      device = ${DEVICE_REF};
      modules = [ ./install.nix ./identity.nix ];
    };
  };
}
EOF
cp "$IDENTITY" "$WORKDIR/identity.nix"

# Resolve the tag to a lockfile now, so the installed device is fully pinned.
(cd "$WORKDIR" && "$NIX_BIN" --extra-experimental-features "nix-command flakes" \
  flake lock --accept-flake-config >/dev/null)

# Install-day facts live in the device flake, not the release: an update must
# never re-decide the layout or stateVersion of a disk already formatted.
write_facts() { # extra line, e.g. the stateVersion
  cat > "$WORKDIR/install.nix" <<EOF
# Generated by librepod-install: this device as installed. OS updates never
# change it; edit only if the disk itself is replaced.
{
  imports = [ ./disk.nix ];
  disko.devices.disk.main.device = "$DISK";
  $1
}
EOF
}
SRC="$("$NIX_BIN" --extra-experimental-features "nix-command flakes" eval --raw --impure \
  --expr "(builtins.getFlake \"path:$WORKDIR\").inputs.librepod.outPath")"
install -m 644 "$SRC/modules/disko/default.nix" "$WORKDIR/disk.nix"
write_facts ""
# The release's default for new installs, frozen from now on.
SV="$("$NIX_BIN" --extra-experimental-features "nix-command flakes" eval --raw \
  "$WORKDIR#nixosConfigurations.$NAME.config.system.stateVersion")"
[[ "$SV" =~ ^[0-9]+\.[0-9]+$ ]] || { echo "unexpected stateVersion: $SV"; exit 1; }
write_facts "system.stateVersion = \"$SV\";"

echo "==> partitioning + formatting via disko (DESTROYS the disk)"
"$DISKO_BIN" --flake "$WORKDIR#$NAME" --mode destroy,format,mount

echo "==> installing NixOS"
install -d -m 700 "$MNT/etc/nixos"
install -m 600 "$WORKDIR/identity.nix" "$MNT/etc/nixos/identity.nix"
install -m 644 "$WORKDIR/flake.nix" "$MNT/etc/nixos/flake.nix"
install -m 644 "$WORKDIR/flake.lock" "$MNT/etc/nixos/flake.lock"
install -m 644 "$WORKDIR/install.nix" "$MNT/etc/nixos/install.nix"
install -m 644 "$WORKDIR/disk.nix" "$MNT/etc/nixos/disk.nix"
if [ "$DEVICE_REF" = "./hardware.nix" ]; then
  install -m 644 "$WORKDIR/hardware.nix" "$MNT/etc/nixos/hardware.nix"
fi

"$NIXOS_INSTALL_BIN" --flake "$WORKDIR#$NAME" --no-root-passwd

echo "==> installed $NAME ($DEVICE on $DISK, $TAG). Reboot into the device when ready."
